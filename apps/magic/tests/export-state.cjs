const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict'),ts=require('../node_modules/typescript');
const c=vm.createContext({exports:{}});
vm.runInContext(ts.transpileModule(fs.readFileSync(path.join(__dirname,'../ui/export-state.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,c);
const state=c.exports.exportIconState;
const good={export_ready:true,export:{path:'/final.mp4',exists:true},validation:{valid:true}};
assert.equal(state(good,false,'',false),'ready');
assert.equal(state(good,false,'',true),'idle');
assert.equal(state({...good,export_ready:false},false,'',false),'idle');
assert.equal(state({...good,validation:{valid:false}},false,'',false),'idle');
assert.equal(state({export:{path:'/old.mp4',exists:true}},false,'',false),'idle');
assert.equal(state(good,true,'',false),'running');
assert.equal(state(good,false,'failed',false),'error');
console.log('Export icon requires validated current output; existence alone never turns it green');
